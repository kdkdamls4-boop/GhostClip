"""
Модуль журнала аудита (Audit Logger).
Безопасно фиксирует события доступа к буферу обмена без утечки секретов.
"""

import datetime
# datetime — работа с датой и временем.

import threading
# threading — потоки. Нужен Lock (замок).

from .detector import detect_secret, mask_secret
# Точка перед detector = «из соседнего файла detector.py в этой же папке».

LOG_FILE_PATH = "clipboard_access.log"
# Имя файла журнала. ЗАГЛАВНЫЕ буквы = константа (не меняется).
# Путь относительный: файл появится в папке, ИЗ КОТОРОЙ запустили программу.

_log_lock = threading.Lock()
# Замок, чтобы два потока не писали в файл одновременно и строки не перемешались.


def log_audit(event: str, process: str, content: str, extra: str = ""):
    # event   — тип события, например "SECRET_ARMED"
    # process — какая программа скопировала, например "chrome.exe"
    # content — что скопировали
    # extra   — дополнительная инфа (необязательно, по умолчанию пустая строка "")
    """
    Записывает событие буфера в файл журнала `clipboard_access.log`.
    Секреты никогда не пишутся в открытом виде — только маскированными!
    """
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    # .now() — текущие дата и время.
    # .strftime(...) — превратить в строку по шаблону: %Y год, %m месяц, %d день,
    # %H часы, %M минуты, %S секунды → "2026-10-23 10:16:13"

    # Безопасное отображение контента
    sec_info = detect_secret(content)
    # Либо None (не секрет), либо кортеж ("API_KEY", "OpenAI API Key").

    if sec_info:
        # Кортеж считается «истиной», None — «ложью».
        safe_content = f"{mask_secret(content)} [{sec_info[1]}]"
        # sec_info[1] — второй элемент кортежа (описание). Нумерация с НУЛЯ!
        # Пример результата: "sk-p•••ef [OpenAI API Key]"
    else:
        # Обрезаем длинный текст
        content_clean = content.strip().replace("\r\n", " ").replace("\n", " ")
        # .replace(что, на_что) — заменить. "\r\n" и "\n" — переносы строк.
        # Методы можно вызывать цепочкой, один за другим.

        if len(content_clean) > 80:
            safe_content = f"{content_clean[:80]}... [всего {len(content_clean)} симв.]"
            # [:80] — первые 80 символов.
        else:
            safe_content = content_clean
        # ⚠️ ЗАМЕЧАНИЕ: обычный текст пишется в лог ОТКРЫТО.
        # Если detector.py не распознал какой-то секрет, он попадёт в лог как есть.

    log_entry = (
        # Строки в скобках подряд без запятых автоматически склеиваются в одну.
        f"[{now_str}] [{event}]\n"
        f"Процесс: {process}\n"
        f"Контент: {safe_content}\n"
        # \n — перенос строки.
    )
    if extra:
        # Пустая строка "" = ложь. То есть «если extra не пустой».
        log_entry += f"Инфо: {extra}\n"
        # += — «добавить к тому, что уже есть». То же, что log_entry = log_entry + ...
    log_entry += "-" * 50 + "\n"
    # "-" * 50 — строку можно умножить: получится 50 дефисов подряд (разделитель).

    with _log_lock:
        # Захватываем замок: пока мы пишем, другие потоки ждут.
        try:
            with open(LOG_FILE_PATH, "a", encoding="utf-8") as f:
                # open(файл, режим) — открыть файл.
                #   "a" = append, дописать в конец (не стирая старое).
                #   "w" стёр бы файл, "r" — только чтение.
                # encoding="utf-8" — чтобы русские буквы не превратились в кракозябры.
                # as f — открытый файл теперь доступен под именем f.
                # with сам закроет файл после блока.
                f.write(log_entry)
        except Exception as e:
            # as e — сохранить саму ошибку в переменную e, чтобы показать её.
            print(f"[!] Ошибка записи в журнал: {e}")
